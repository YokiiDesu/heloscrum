import {readFile, writeFile, mkdir, access, chmod, copyFile} from 'node:fs/promises';
import {constants} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import os from 'node:os';

const repo = fileURLToPath(new URL('../', import.meta.url));
const [action, home, target, shortcut] = process.argv.slice(2);
const quote = value => "'" + value.replaceAll("'", "'\\''") + "'";
const validPath = value => typeof value === 'string' && path.isAbsolute(value) && !/[\x00-\x1f\x7f]/.test(value);
try {
  if (action === 'fingerprint') {
    const directory = target === 'desktop' ? path.join(repo, 'desktop') : repo;
    const text = await readFile(path.join(directory, 'package-lock.json'));
    console.log(createHash('sha256').update(text).update(process.version + process.platform + process.arch).digest('hex'));
  } else if (action === 'saved-root') {
    try {console.log(JSON.parse(await readFile(path.join(home, 'launcher.json'), 'utf8')).root || '');} catch (e) {if (e.code !== 'ENOENT') throw e;}
  } else if (action === 'configure') {
    if (!validPath(home) || !validPath(target)) throw Error('Use absolute folder paths without control characters.');
    await mkdir(target, {recursive: true, mode: 0o700});
    // Create a real, disposable starter project only in a new, empty directory.
    const {readdir} = await import('node:fs/promises');
    if (!(await readdir(target)).length) {
      execFileSync('git', ['init', '--quiet', '--initial-branch=main', target]);
      await writeFile(path.join(target, 'README.md'), '# My HeloScrum workspace\n\nAdd your projects using the project library in HeloScrum.\n');
      await writeFile(path.join(target, '.gitignore'), '.heloscrum/\n.DS_Store\n');
      execFileSync('git', ['-C', target, 'add', 'README.md', '.gitignore']);
      execFileSync('git', ['-C', target, '-c', 'user.name=HeloScrum Setup', '-c', 'user.email=setup@localhost', 'commit', '--quiet', '-m', 'Create local HeloScrum workspace']);
    } else if (!(await access(path.join(target, '.heloscrum')).then(() => true, () => false))) {
      execFileSync('git', ['-C', target, 'rev-parse', '--show-toplevel'], {stdio: 'pipe'});
    }
    await mkdir(home, {recursive: true, mode: 0o700});
    await writeFile(path.join(home, 'launcher.json'), JSON.stringify({root: target, node: process.execPath, repo, path: process.env.PATH}, null, 2) + '\n', {mode: 0o600});
    await chmod(path.join(home, 'launcher.json'), 0o600);
    const body = `#!/bin/bash\n# HeloScrum desktop launcher; generated by setup-desktop.sh.\nset -e\nexport HELOSCRUM_DESKTOP_HOME=${quote(home)}\nprintf '\\n  HeloScrum — opening your local workspace\\n\\n'\nexec ${quote(process.execPath)} ${quote(path.join(repo, 'scripts/desktop.mjs'))}\n`;
    const launcher = path.join(home, 'HeloScrum.command');
    await writeFile(launcher, body, {mode: 0o700});
    await chmod(launcher, 0o700);
    if (shortcut === 'yes' && process.platform === 'darwin') {
      const bundle = path.join(os.homedir(), 'Applications/HeloScrum.app');
      const marker = path.join(bundle, 'Contents/heloscrum-launcher');
      if (await access(bundle).then(() => true, () => false)) {
        if (!await access(marker).then(() => true, () => false)) throw Error('An unrelated HeloScrum.app already exists in your Applications folder. It was left untouched; use the generated HeloScrum.command.');
      }
      await mkdir(path.join(bundle, 'Contents/MacOS'), {recursive: true});
      await mkdir(path.join(bundle, 'Contents/Resources'), {recursive: true});
      await writeFile(marker, 'HeloScrum source desktop launcher\n');
      await writeFile(path.join(bundle, 'Contents/MacOS/launch'), `#!/bin/bash\nexport HELOSCRUM_DESKTOP_HOME=${quote(home)}\nexec ${quote(process.execPath)} ${quote(path.join(repo, 'scripts/desktop.mjs'))} >> ${quote(path.join(home, 'logs/launcher.log'))} 2>&1\n`, {mode: 0o700});
      await chmod(path.join(bundle, 'Contents/MacOS/launch'), 0o700);
      await writeFile(path.join(bundle, 'Contents/Info.plist'), '<?xml version="1.0" encoding="UTF-8"?><!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd"><plist version="1.0"><dict><key>CFBundleExecutable</key><string>launch</string><key>CFBundleIdentifier</key><string>dev.heloscrum.desktop-launcher</string><key>CFBundleName</key><string>HeloScrum</string><key>CFBundleDisplayName</key><string>HeloScrum</string><key>CFBundlePackageType</key><string>APPL</string><key>CFBundleIconFile</key><string>heloscrum.icns</string></dict></plist>');
      await copyFile(path.join(repo, 'desktop/icon.icns'), path.join(bundle, 'Contents/Resources/heloscrum.icns'));
      console.log(`Application shortcut: ${bundle}`);
    } else if (shortcut === 'yes' && process.platform === 'linux') {
      const dir = path.join(process.env.XDG_DATA_HOME || path.join(os.homedir(), '.local/share'), 'applications');
      await mkdir(dir, {recursive: true});
      const desktopQuote = value => '"' + value.replace(/([\\"`$])/g, '\\$1').replaceAll('%', '%%') + '"';
      const file = path.join(dir, 'heloscrum.desktop');
      try {if (!(await readFile(file, 'utf8')).includes('X-HeloScrum-Launcher=true')) throw Error('An unrelated heloscrum.desktop exists. It was left untouched.');} catch (e) {if (e.code !== 'ENOENT') throw e;}
      await writeFile(file, `[Desktop Entry]\nType=Application\nName=HeloScrum\nComment=Your local coding-agent workspace\nExec=${desktopQuote(launcher)}\nIcon=${path.join(repo, 'desktop/icon.png')}\nTerminal=false\nCategories=Development;\nX-HeloScrum-Launcher=true\n`, {mode: 0o700});
      console.log(`Application shortcut: ${file}`);
    }
    console.log(`Next launch: ${launcher}`);
  } else if (action === 'electron-check') {
    const {createRequire} = await import('node:module');
    const require = createRequire(path.join(repo, 'desktop/package.json'));
    await access(require('electron'), constants.X_OK);
    console.log(`Electron ${require('electron/package.json').version} downloaded`);
  } else throw Error('Unknown setup operation');
} catch (error) {console.error(error.message); process.exitCode = 1;}
