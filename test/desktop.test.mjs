test('desktop backend uses a real free loopback port, authenticates and survives graceful restart', {timeout: 45000}, async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'Helo desktop with spaces '));
  execFileSync('git', ['init', '--quiet', root]);
  t.after(() => rm(root, {recursive: true, force: true}));
  const env = {...process.env};
  for (const key of Object.keys(env)) if (/^(HERDR|HELOSCRUM)_/.test(key)) delete env[key];
  const first = startBackend({node: process.execPath, codeRoot, root, port: 0, env});
  t.after(() => first.stop());
  const {url} = await first.ready;
  const guide=await fetch(url+'/help/blog/connect-your-existing-agents.html');
  assert.equal(guide.status,200);
  assert.match(guide.headers.get('content-type'),/^text\/html/);
  assert.match(guide.headers.get('content-security-policy'),/frame-ancestors 'none'/);
  assert.match(await guide.text(),/CODEX_THREAD_ID/);
  const localGuide=await fetch(url+'/help/blog/local-llms.html');
  assert.equal(localGuide.status,200);
  assert.match(localGuide.headers.get('content-security-policy'),/frame-ancestors 'none'/);
  const ball=await fetch(url+'/help/demos/red-ball.html');
  assert.equal(ball.status,200);
  const ballPolicy=ball.headers.get('content-security-policy');
  assert.match(ballPolicy,/sandbox allow-scripts/);
  assert.match(ballPolicy,/frame-ancestors 'self'/);
  assert.match(ballPolicy,/connect-src 'none'/);
  assert.doesNotMatch(ballPolicy,/allow-same-origin|unsafe-inline/);
  const original=await fetch(url+'/help/demos/red-ball-original.html');
  assert.equal(original.headers.get('content-disposition'),'attachment; filename="red-ball.html"');
  assert.match(original.headers.get('content-security-policy'),/sandbox; frame-ancestors 'none'/);
  // The opaque demo origin cannot call the local application API.
  assert.equal((await fetch(url+'/api/session',{headers:{Origin:'null','Sec-Fetch-Site':'cross-site'}})).status,403);
  for(const asset of ['blog.css','style.css','pages.css','site.js','assets/mark.svg','integrations.html'])assert.equal((await fetch(url+'/help/'+asset)).status,200,asset);
  assert.equal((await fetch(url+'/help/blog/connect-your-existing-agents.html',{method:'HEAD'})).status,200);
  assert.equal((await fetch(url+'/help/blog/connect-your-existing-agents.html',{method:'POST'})).status,405);
  for(const file of ['package.json','%2e%2e%2fpackage.json','.heloscrum/state.json'])assert.equal((await fetch(url+'/help/'+file)).status,404,file);
  assert.deepEqual(await first.activity(),{tasks:[]});
  assert.match(url, /^http:\/\/127\.0\.0\.1:[1-9]\d+$/);
  assert.equal((await fetch(url + '/api/state')).status, 401);
  const {token} = await (await fetch(url + '/api/session')).json();
  const headers = {'X-HeloScrum-Token': token};
  const state = await (await fetch(url + '/api/state', {headers})).json();
  assert.equal(path.resolve(state.project.path), path.resolve(root));
  const owner = JSON.parse(await readFile(path.join(root, '.heloscrum/api-owner.json'), 'utf8'));
  assert.equal(owner.url, url);
  const save = await fetch(url + '/api/project-settings/conversation', {method: 'POST', headers: {...headers, 'Content-Type':'application/json'}, body: JSON.stringify({project: root, style:'concise', expectedRevision:0})});
  assert.equal(save.status, 200);
  await first.stop();
  await assert.rejects(fetch(url));
  assert.ok(JSON.parse(await readFile(path.join(root, '.heloscrum/state.json'), 'utf8')));
  const next = startBackend({node: process.execPath, codeRoot, root, port: 0, env});
  t.after(() => next.stop());
  const reopened = await next.ready;
  assert.equal((await fetch(reopened.url + '/api/state', {headers})).status, 401);
  const nextToken = (await (await fetch(reopened.url + '/api/session')).json()).token;
  const settings = await (await fetch(reopened.url + '/api/project-settings', {headers:{'X-HeloScrum-Token':nextToken}})).json();
  assert.equal(settings.conversation.style, 'concise');
  await next.stop();
});
test('backend startup failure and early stop clean up only the owned child', {timeout: 25000}, async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'Helo desktop failure '));
  t.after(() => rm(root, {recursive: true, force: true}));
  const missing = startBackend({node: path.join(root, 'missing-node'), codeRoot, root, port: 0});
  await assert.rejects(missing.ready, /ENOENT/);
  await missing.stop();
  await writeFile(path.join(root, 'server.mjs'), 'process.on("message",()=>{});setInterval(()=>{},1000);');
  const timeout = startBackend({node: process.execPath, codeRoot: root, root, port: 0, timeout: 100});
  await assert.rejects(timeout.ready, /did not become ready/);
  assert.equal(timeout.stopped, true);
  assert.ok(timeout.child.signalCode || timeout.child.exitCode !== null);
});
test('desktop setup handles spaces and quotes, reruns without changing the existing workspace', {skip: process.platform === 'win32'}, async t => {
  const base = await mkdtemp(path.join(os.tmpdir(), "Helo setup's folder "));
  t.after(() => rm(base, {recursive: true, force: true}));
  const home = path.join(base, 'app home'), root = path.join(base, 'my workspace');
  const args = [path.join(codeRoot, 'scripts/desktop-setup.mjs'), 'configure', home, root, 'no'];
  execFileSync(process.execPath, args);
  const before = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], {encoding: 'utf8'});
  execFileSync(process.execPath, args);
  assert.equal(execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], {encoding: 'utf8'}), before);
  const launcher = path.join(home, 'HeloScrum.command');
  assert.equal(spawnSync('bash', ['-n', launcher]).status, 0);
  assert.equal(JSON.parse(await readFile(path.join(home, 'launcher.json'), 'utf8')).root, root);
  const occupied = path.join(base, 'not a project');
  await mkdir(occupied); await writeFile(path.join(occupied, 'keep.txt'), 'unrelated');
  assert.throws(() => execFileSync(process.execPath, [args[0], 'configure', home, occupied, 'no'], {stdio: 'pipe'}));
  assert.equal(await readFile(path.join(occupied, 'keep.txt'), 'utf8'), 'unrelated');
});
