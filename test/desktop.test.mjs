test('desktop never treats a different local port or privileged URL as its renderer origin', () => {
  const origin = 'http://127.0.0.1:54321';
  assert.equal(sameOrigin(origin + '/?view=work', origin), true);
  for (const url of ['http://127.0.0.1:54322/', 'http://127.0.0.1.evil.test:54321/', 'file:///tmp/example', 'javascript:alert(1)', 'data:text/html,test', 'http://localhost:54321/']) assert.equal(sameOrigin(url, origin), false, url);
  for (const url of ['file:///etc/passwd', 'javascript:alert(1)', 'vscode://file/a', 'https://user:secret@example.com']) assert.equal(externalLink(url), null, url);
  assert.equal(externalLink('https://example.com/help'), 'https://example.com/help');
});
test('desktop does not silently quit active or unknown agent state', () => {
  assert.equal(hasActiveWork({tasks: []}), false);
  assert.equal(hasActiveWork({tasks: [{pane: 'native-session'}]}), true);
  assert.equal(hasActiveWork({tasks: [{phase: 'starting'}]}), true);
  assert.equal(hasActiveWork(undefined), true);
  assert.equal(hasActiveWork({error: 'offline'}), true);
});
